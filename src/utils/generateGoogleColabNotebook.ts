/**
 * Triggers client-side download of the complete Google Colab .ipynb file
 */
export function downloadGoogleColabNotebook(): void {
  const jsonContent = buildGoogleColabNotebookJson();
  const blob = new Blob([jsonContent], { type: 'application/x-ipynb+json;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.setAttribute('download', 'LeadGen_ML_DL_Intelligence_Enterprise_14_Models.ipynb');
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
