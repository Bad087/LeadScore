          "    \"\"\"\n",
          "    Binary Focal Loss: Down-weights well-classified non-converting negatives:\n",
          "    FL(p_t) = -alpha * (1 - p_t)^gamma * log(p_t)\n",
          "    \"\"\"\n",
          "    def __init__(self, alpha: float = 0.65, gamma: float = 2.0):\n",
          "        super().__init__()\n",
